"""The neutral station runs the stock TEAx study lifecycle, and ``verify`` completes on it.

study-layer-to-codegen's fixture, ``tests/fixtures/study_station/``, is the project the moved
study tools are proved on. Its committed package was generated by this branch from
``models/station.sysml``. Its route, ``studies/study_route.py``, runs that package as committed
through the stock lifecycle of ``test_numeric_evidence_teax.py``: TEAx's own seal-checking
loader, a ``StudyRunner`` over a prepared proposal list, and a reopened store read through
``StudyQuery``. ``StudyQuery`` is the surface ``verify`` samples, so a verdict read here is the
verdict ``verify`` re-derives.

Expected values are hand-derived from the model, never read back:

- baseline ``required_flow = 0.30 - 0.005 * 12.0 = 0.24``;
- baseline ``annual_cost = 0.24 * 8.0 * 0.10 * 1000.0 = 192.0``;
- ``pump_fit`` holds exactly when ``installed_capacity >= 0.30 - 0.005 * basin_area``. Over
  the grid the required flows are 0.28, 0.26, 0.24 and 0.22, so no point sits on the
  boundary and both verdicts appear.

The ``verify`` tests are fusion-tea ``tests/study/test_verify.py`` at ``b06585709``: the ones
that hold on any package, re-pointed at the station. The sealed-identity pair comes from the
same tree's ``test_stock_route.py``. The fixture is its own project, so every test here runs
with ``SYSML_CODEGEN_PROJECT_ROOT`` naming it.
"""

