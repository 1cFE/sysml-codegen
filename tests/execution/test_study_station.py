# --------------------------------------------------------------- the lifecycle (KB4)


def test_the_station_package_runs_the_stock_study_lifecycle(
    route: ModuleType, tmp_path: Path
) -> None:
    (baseline,), _ = route.run_points(
        "station-kb4-baseline", [{}], package_dir=STATION_PACKAGE, work=tmp_path / "baseline"
    )
    assert baseline.outputs[REQUIRED_FLOW] == pytest.approx(0.24)
    assert baseline.outputs[ANNUAL_COST] == pytest.approx(192.0)
    assert list(baseline.verdicts.values()) == ["satisfied"]

    cases, _ = route.run_points(
        "station-kb4-grid", route.GRID, package_dir=STATION_PACKAGE, work=tmp_path / "grid"
    )
    (constraint_id,) = {cid for case in cases for cid in case.verdicts}
    observed = {
        (case.inputs[BASIN_AREA], case.inputs[CAPACITY]): case.verdicts[constraint_id]
        for case in cases
    }
    expected = {
        (point[BASIN_AREA], point[CAPACITY]): (
            "satisfied" if (point[BASIN_AREA], point[CAPACITY]) in SATISFIED else "violated"
        )
        for point in route.GRID
    }
    assert observed == expected
    for case in cases:
        flow = 0.30 - 0.005 * case.inputs[BASIN_AREA]
        assert case.outputs[REQUIRED_FLOW] == pytest.approx(flow)
        assert case.outputs[ANNUAL_COST] == pytest.approx(flow * 8.0 * 0.10 * 1000.0)


def test_the_route_reproduces_the_committed_baseline(route: ModuleType, tmp_path: Path) -> None:
    """``studies/baseline/`` is what the route deposits, byte for byte (PROVENANCE.md)."""
