SATISFIED = {(4.0, 0.30), (8.0, 0.30), (12.0, 0.25), (12.0, 0.30), (16.0, 0.25), (16.0, 0.30)}


def _import_from_studies(name: str) -> ModuleType:
    """A module of the fixture's studies directory, imported the way ``verify`` imports one."""
    if str(STUDIES) not in sys.path:
        sys.path.insert(0, str(STUDIES))
    __import__(name)
    return sys.modules[name]


