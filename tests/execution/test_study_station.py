"""The neutral station package runs the stock TEAx study lifecycle (KB4).

study-layer-to-codegen's fixture, ``tests/fixtures/study_station/``, is the project the moved
study tools are proved on. Its committed package was generated by this branch from
``models/station.sysml``. This lane runs that package, as committed, through the same stock
lifecycle as ``test_numeric_evidence_teax.py``: TEAx's own seal-checking loader, a
``StudyRunner`` over a prepared proposal list, and a reopened store read through
``StudyQuery``. ``StudyQuery`` is the surface ``verify`` samples, so a verdict read here is
the verdict ``verify`` will re-derive.

Expected values are hand-derived from the model, never read back:

- baseline ``required_flow = 0.30 - 0.005 * 12.0 = 0.24``;
- baseline ``annual_cost = 0.24 * 8.0 * 0.10 * 1000.0 = 192.0``;
- ``pump_fit`` holds exactly when ``installed_capacity >= 0.30 - 0.005 * basin_area``. Over
  the grid the required flows are 0.28, 0.26, 0.24 and 0.22, so no point sits on the
  boundary and both verdicts appear.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import pytest

from tests.execution.real_teax import package_loader

pytestmark = pytest.mark.execution

FIXTURE = Path(__file__).resolve().parents[1] / "fixtures" / "study_station"
PACKAGE = FIXTURE / "pkg" / "station_study"
NAME = "station_study"

STATION = "PumpStation__station__"
REQUIRED_FLOW = STATION + "demand__required_flow"
ANNUAL_COST = STATION + "pumping__annual_cost"
BASIN_AREA = STATION + "basin_area"
CAPACITY = STATION + "installed_capacity"

#: ``(basin_area, installed_capacity)`` points where ``pump_fit`` holds; every other grid
#: point violates it.
SATISFIED = {(4.0, 0.30), (8.0, 0.30), (12.0, 0.25), (12.0, 0.30), (16.0, 0.25), (16.0, 0.30)}
GRID = [
    {BASIN_AREA: area, CAPACITY: capacity}
    for area in (4.0, 8.0, 12.0, 16.0)
    for capacity in (0.20, 0.25, 0.30)
]


def run_stock_lifecycle(
    package: Path, study_id: str, proposals: Sequence[Mapping[str, float]], work: Path
) -> list[Any]:
    """Run ``proposals`` through the stock study lifecycle and return the reopened cases."""
    from simkit.evaluation.evaluator import PreparedEvaluator
    from simkit.study.bridge import CandidateBridge
    from simkit.study.definition import StudyDefinition
    from simkit.study.identity import digest_of
    from simkit.study.policy import ObjectivePolicy
    from simkit.study.query import StudyQuery
    from simkit.study.runner import StudyRunner
    from simkit.study.store import StudyStore
    from simkit.study.strategy import PreparedListStrategy

    work.mkdir(parents=True)
    evaluator = PreparedEvaluator(
        package_loader(package, NAME, work / "link"),
        package / "pipelines" / "pipeline.yaml",
        expects_constraint_report=True,
    )
    # Fails closed on a key the package does not declare, before anything runs.
    bridge = CandidateBridge(evaluator.entry_models)
    for proposal in proposals:
        bridge.build(proposal)
    contract = json.loads((package / "contracts" / "model_contract.json").read_text())
    points = [dict(proposal) for proposal in proposals]
    definition = StudyDefinition(
        study_id=study_id,
        entry_models=evaluator.entry_models,
        strategy=PreparedListStrategy(points),
        validate_proposal=lambda proposal: proposal,
        policy=ObjectivePolicy((), {}),
        executable_fingerprint=evaluator.fingerprint,
        model_contract_fingerprint=contract["semantic_fingerprint"],
        input_schema_version="v1",
        evidence_schema_version=evaluator.EVIDENCE_SCHEMA_VERSION,
        study_definition_fingerprint=digest_of(points),
    )
    db = work / "study.db"
    store = StudyStore.create_or_open(db, definition.compatibility())
    try:
        store.acquire_lease()
        StudyRunner(store, definition, evaluator).run()
        store.release_lease()
    finally:
        store.close()

    reopened = StudyStore.create_or_open(db, definition.compatibility())
    try:
        cases = StudyQuery(reopened, package).cases()
    finally:
        reopened.close()
    assert [case.state for case in cases] == ["completed"] * len(points)
    for case in cases:
        assert case.executable_fingerprint == evaluator.fingerprint
        assert case.evidence_digest
    return cases


def test_the_station_package_runs_the_stock_study_lifecycle(tmp_path: Path) -> None:
    (baseline,) = run_stock_lifecycle(PACKAGE, "station-baseline", [{}], tmp_path / "baseline")
    assert baseline.outputs[REQUIRED_FLOW] == pytest.approx(0.24)
    assert baseline.outputs[ANNUAL_COST] == pytest.approx(192.0)
    assert list(baseline.verdicts.values()) == ["satisfied"]

    cases = run_stock_lifecycle(PACKAGE, "station-grid", GRID, tmp_path / "grid")
    (constraint_id,) = {cid for case in cases for cid in case.verdicts}
    observed = {
        (case.inputs[BASIN_AREA], case.inputs[CAPACITY]): case.verdicts[constraint_id]
        for case in cases
    }
    expected = {
        (point[BASIN_AREA], point[CAPACITY]): (
            "satisfied" if (point[BASIN_AREA], point[CAPACITY]) in SATISFIED else "violated"
        )
        for point in GRID
    }
    assert observed == expected
    for case in cases:
        flow = 0.30 - 0.005 * case.inputs[BASIN_AREA]
        assert case.outputs[REQUIRED_FLOW] == pytest.approx(flow)
        assert case.outputs[ANNUAL_COST] == pytest.approx(flow * 8.0 * 0.10 * 1000.0)
