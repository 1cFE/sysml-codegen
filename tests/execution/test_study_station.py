def test_a_planted_channel_deviation_fails_naming_case_and_channel(
    grid: Path, oracle: ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Named channels must agree at rel < 1e-9 (``sysml_codegen/study/verify.py:10-11``)."""
    real = oracle.evaluate

    def skewed(point: dict[str, float]) -> dict[str, float]:
        values: dict[str, float] = dict(real(point))
        values[ANNUAL_COST] *= 1.000001
        return values

    monkeypatch.setattr(oracle, "evaluate", skewed)
    with pytest.raises(verify.VerifyError) as exc:
        build_summary(grid)
    assert ANNUAL_COST in str(exc.value) and "relative deviation" in str(exc.value)


def test_a_planted_verdict_mismatch_fails_naming_the_constraint(
    grid: Path, oracle: ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Every verdict is re-derived, and a disagreement refuses (``verify.py:12-20``).

    The plant binds the capacity operand to the pump head (8.0), which covers every grid
    flow, so re-derivation reads satisfied where the store records violated.
    """
    real = oracle.operand_bindings

    def rebound() -> dict[str, dict[str, dict[str, str]]]:
        table: dict[str, dict[str, dict[str, str]]] = real()
        table[PUMP_FIT]["capacity"] = {"kind": "input", "key": PREFIX + "pump_head"}
        return table

    monkeypatch.setattr(oracle, "operand_bindings", rebound)
    with pytest.raises(verify.VerifyError) as exc:
        build_summary(grid)
    assert "pump_fit" in str(exc.value) and "verdict mismatch" in str(exc.value)


def test_a_missing_operand_bindings_attribute_fails_closed(
    grid: Path, oracle: ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Without published bindings the tool refuses rather than guesses (``verify.py:16-20``)."""
    monkeypatch.delattr(oracle, "operand_bindings")
    with pytest.raises(verify.VerifyError) as exc:
        build_summary(grid)
    assert "operand_bindings" in str(exc.value) and "does not guess" in str(exc.value)


def test_an_unresolvable_binding_fails_naming_the_constraint_and_operand(
    grid: Path, oracle: ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Anything unresolved is a failure naming the constraint and operand (``verify.py:18-19``)."""
    real = oracle.operand_bindings

    def broken() -> dict[str, dict[str, dict[str, str]]]:
        table: dict[str, dict[str, dict[str, str]]] = real()
        table[PUMP_FIT]["capacity"] = {"kind": "input", "key": "no_such__key"}
        return table

    monkeypatch.setattr(oracle, "operand_bindings", broken)
    with pytest.raises(verify.VerifyError) as exc:
        build_summary(grid)
    assert PUMP_FIT in str(exc.value) and "capacity" in str(exc.value)
    assert "no_such__key" in str(exc.value)


def test_a_store_bound_to_another_identity_is_refused(grid: Path, tmp_path: Path) -> None:
    """The store ran under the sealed fingerprint, which a route claiming an adapter never
    earned: its cases are refused as not the gated identity."""
    package = STATION_PACKAGE
    effective = identity.build_effective(
        package_name=NAME,
        package_root=package,
        sealed_fingerprint=manifest_mod.read_executable_fingerprint(package),
        allowed_modified=[
            ("inputs/station_params.json",
             manifest_mod.sha256_file(package / "inputs/station_params.json")),
        ],
        adapter_sources=[
            ("studies/oracle_entry.py", manifest_mod.sha256_file(STUDIES / "oracle_entry.py")),
        ],
        glue_ledger=[],
    )
    path = common.write_document(effective, tmp_path / "package_identity.json")
    with pytest.raises(verify.VerifyError) as exc:
        verify.build_summary(package, STATION_MANIFEST, path, [grid], 12, None, [])
    assert "not the gated identity" in str(exc.value)


def test_an_empty_result_is_a_broken_input_not_a_clean_pass(grid: Path, tmp_path: Path) -> None:
    """No completed cases is a mechanical failure, never an empty pass."""
    from simkit.study.store import StudyStore

    work = tmp_path / "_work"
    shutil.copytree(grid.parent, work)  # the evidence artifacts travel with the store
    db = work / grid.name
    store = StudyStore(db)
    store.conn.execute("UPDATE cases SET state = 'failed'")
    store.conn.commit()
    store.close()
    with pytest.raises(verify.VerifyError) as exc:
        build_summary(db)
    assert "no completed cases" in str(exc.value)


def test_the_stores_are_never_written(grid: Path, simkit_root: Path, tmp_path: Path) -> None:
    before = hashlib.sha256(grid.read_bytes()).hexdigest()
    assert run_verify(grid, tmp_path / "summary.json", simkit_root).returncode == 0
    assert hashlib.sha256(grid.read_bytes()).hexdigest() == before


# --------------------------------------------------------------- the sealed identity


def _seal(package: Path) -> dict[str, Any]:
    seal: dict[str, Any] = json.loads(
        (package / "contracts" / "package_contract.json").read_text()
    )
    return seal


def test_stock_strict_loader_accepts_the_sealed_package(tmp_path: Path) -> None:
    from simkit.evaluation.package_load import ProvisionalPackageLoader

    seal = _seal(STATION_PACKAGE)
    assert seal["runtime_contract_version"] == "2.0.0"
    differing = [
        relative
        for relative, digest in seal["artifact_hashes"].items()
        if hashlib.sha256((STATION_PACKAGE / relative).read_bytes()).hexdigest() != digest
    ]
    assert differing == []

    module, fingerprint = ProvisionalPackageLoader(
        package_dir=STATION_PACKAGE,
        package_name=NAME,
        link_root=tmp_path / "link",
        strict=True,
    ).load()
    assert module.__name__ == NAME
    assert fingerprint == seal["executable_fingerprint"]


def test_sealed_identity_is_the_executable_fingerprint() -> None:
    document = identity.build_sealed(package_name=NAME, package_root=STATION_PACKAGE)
    block = document["identity"]
    assert block["digest"] == block["sealed_executable_fingerprint"]
    sealed = _seal(STATION_PACKAGE)["executable_fingerprint"]
    assert block["sealed_executable_fingerprint"] == sealed
    assert block["allowed_modified_files"] == []
    assert block["adapter_sources"] == []
    assert document["glue_ledger"] == []
